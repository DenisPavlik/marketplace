// Builds demo data for Stoop.
//
//   node --env-file=.env.local scripts/seed/seed.mjs
//
// 1. Re-uploads every catalog photo to ImageKit (cached in .uploads.json, so reruns are cheap).
// 2. Writes scripts/seed/seed.sql: listings, conversations, messages and favorites for the
//    seed accounts. Run that SQL against the database (Supabase SQL editor or MCP).
//
// Seed users are created separately (see README → Demo data); their ids are derived from
// their key with UUIDv5 so this script and the SQL agree without a lookup.

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ImageKit from "@imagekit/nodejs";

const here = dirname(fileURLToPath(import.meta.url));
const catalog = JSON.parse(readFileSync(join(here, "catalog.json"), "utf8"));
const cachePath = join(here, ".uploads.json");
const cache = existsSync(cachePath) ? JSON.parse(readFileSync(cachePath, "utf8")) : {};

// RFC 4122 v5 UUID in the URL namespace, matching Python's uuid.uuid5(NAMESPACE_URL, name).
function uuidv5(name) {
  const ns = Buffer.from("6ba7b8119dad11d180b400c04fd430c8", "hex");
  const hash = createHash("sha1").update(Buffer.concat([ns, Buffer.from(name)])).digest();
  hash[6] = (hash[6] & 0x0f) | 0x50;
  hash[8] = (hash[8] & 0x3f) | 0x80;
  const h = hash.subarray(0, 16).toString("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

const userId = (key) => uuidv5(`stoop-seed-${key}`);
const listingId = (key) => uuidv5(`stoop-seed-listing-${key}`);
const sql = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const ago = (minutes) => `now() - interval '${Math.round(minutes)} minutes'`;

async function uploadAll() {
  const ik = new ImageKit({ privateKey: process.env.IK_PRIVATE_KEY });
  for (const listing of catalog.listings) {
    for (const [i, img] of listing.images.entries()) {
      if (cache[img.url]) continue;
      process.stdout.write(`Uploading ${listing.key} #${i + 1}… `);
      const res = await ik.files.upload({
        file: img.url,
        fileName: `${listing.key}-${i + 1}.${img.url.includes("rawpixel") ? "webp" : "jpg"}`,
        folder: "/stoop/seed",
        useUniqueFileName: false,
        overwriteFile: true,
      });
      cache[img.url] = { fileId: res.fileId, path: res.filePath, width: res.width, height: res.height };
      writeFileSync(cachePath, JSON.stringify(cache, null, 2));
      console.log("done");
    }
  }
}

function buildSql() {
  const out = [
    "-- Generated by scripts/seed/seed.mjs. Safe to re-run: it replaces previous seed rows.",
    "begin;",
    `delete from public.listings where id in (${catalog.listings.map((l) => sql(listingId(l.key))).join(", ")});`,
  ];

  for (const s of catalog.sellers) {
    out.push(`update public.profiles set bio = ${sql(s.bio)} where id = ${sql(userId(s.key))};`);
  }

  for (const l of catalog.listings) {
    const images = l.images.map((img) => cache[img.url]).filter(Boolean);
    if (images.length === 0) throw new Error(`No uploaded images for ${l.key}`);
    const created = ago(l.daysAgo * 24 * 60 + (l.key.length * 37) % 600);
    out.push(
      `insert into public.listings (id, seller_id, title, description, price, category, condition, status, images, lat, lng, location_name, created_at, updated_at, is_seed) values (` +
        [
          sql(listingId(l.key)),
          sql(userId(l.seller)),
          sql(l.title),
          sql(l.description),
          l.price,
          sql(l.category),
          sql(l.condition),
          sql(l.status),
          `${sql(JSON.stringify(images))}::jsonb`,
          Math.round(l.lat * 400) / 400,
          Math.round(l.lng * 400) / 400,
          sql(l.locationName),
          created,
          created,
          "true",
        ].join(", ") +
        ");",
    );
  }

  // Conversations give the demo account a lived-in inbox.
  const mayas = catalog.listings.filter((l) => l.seller === "maya" && l.status !== "sold");
  const others = catalog.listings.filter((l) => l.seller !== "maya" && l.status === "active");
  const pick = (list, i) => list[i % list.length];

  const threads = [
    {
      listing: pick(mayas, 0),
      buyer: "kofi",
      unreadFor: "seller",
      messages: [
        ["buyer", 190, "Hi Maya, is this still available?"],
        ["seller", 172, "Hi! Yes it is."],
        ["buyer", 165, "Great. Could I come by tomorrow after 6?"],
        ["seller", 150, "6:30 works. I'm near the Grand Army Plaza side of the park."],
        ["buyer", 12, "Perfect. Would you do a little less if I bring cash?"],
      ],
    },
    {
      listing: mayas.find((l) => l.status === "reserved") ?? pick(mayas, 1),
      buyer: "hannah",
      unreadFor: null,
      messages: [
        ["buyer", 3000, "Hello! Interested in this. Still around?"],
        ["seller", 2950, "It is. Happy to hold it for you until the weekend."],
        ["buyer", 2900, "That would be lovely, thank you. Saturday morning?"],
        ["seller", 2880, "Saturday at 10 works. I'll mark it on hold."],
      ],
    },
    {
      listing: pick(others, 2),
      buyer: "maya",
      unreadFor: "buyer",
      messages: [
        ["buyer", 600, "Hey, is this still for sale?"],
        ["seller", 30, "Yep! Want to come take a look this week?"],
      ],
    },
    {
      listing: pick(others, 7),
      buyer: "maya",
      unreadFor: null,
      messages: [
        ["buyer", 5000, "Hi! Does it come with everything in the photo?"],
        ["seller", 4900, "Everything you see, yes."],
        ["buyer", 4890, "Great, I'll think it over and get back to you."],
      ],
    },
  ];

  for (const t of threads) {
    if (!t.listing) continue;
    const convId = uuidv5(`stoop-seed-conv-${t.listing.key}-${t.buyer}`);
    const buyerId = userId(t.buyer);
    const sellerId = userId(t.listing.seller);
    if (buyerId === sellerId) continue;
    out.push(
      `insert into public.conversations (id, listing_id, buyer_id, seller_id, created_at, is_seed) values (${sql(convId)}, ${sql(listingId(t.listing.key))}, ${sql(buyerId)}, ${sql(sellerId)}, ${ago(t.messages[0][1] + 1)}, true);`,
    );
    for (const [who, minutesAgo, body] of t.messages) {
      out.push(
        `insert into public.messages (conversation_id, sender_id, body, created_at) values (${sql(convId)}, ${sql(who === "buyer" ? buyerId : sellerId)}, ${sql(body)}, ${ago(minutesAgo)});`,
      );
    }
    const last = t.messages.at(-1)[1];
    out.push(
      `update public.conversations set buyer_last_read_at = ${t.unreadFor === "buyer" ? ago(last + 5) : "now()"}, seller_last_read_at = ${t.unreadFor === "seller" ? ago(last + 5) : "now()"} where id = ${sql(convId)};`,
    );
  }

  const saved = others.filter((_, i) => i % 4 === 1).slice(0, 5);
  for (const l of saved) {
    out.push(
      `insert into public.favorites (user_id, listing_id) values (${sql(userId("maya"))}, ${sql(listingId(l.key))}) on conflict do nothing;`,
    );
  }

  out.push("commit;");
  writeFileSync(join(here, "seed.sql"), out.join("\n") + "\n");
  console.log(`Wrote seed.sql: ${catalog.listings.length} listings, ${threads.length} conversations, ${saved.length} saved.`);
}

await uploadAll();
buildSql();
